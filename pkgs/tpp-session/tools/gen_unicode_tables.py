#!/usr/bin/env python3
"""Regenerates src/unicode.rs from the Unicode tables of the running Python.

tpp session reproduces Python's str.isprintable(), str.isspace() and int() for the session list
and for argument parsing, so the tables come from Python itself:

    python3 -I tools/gen_unicode_tables.py > src/unicode.rs
"""
import sys
import unicodedata


def ranges(predicate):
    start = None
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            hit = start is not None  # surrogates are not chars in Rust: extend the range over them
        else:
            hit = predicate(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            yield start, code - 1
            start = None
    if start is not None:
        yield start, 0x10FFFF


def emit(declaration, doc, items):
    print(f"/// {doc}")
    print(f"pub const {declaration} = &[")
    line = "   "
    for item in items:
        text = f" {item},"
        if len(line) + len(text) > 100:
            print(line)
            line = "   "
        line += text
    print(line)
    print("];")
    print()


def main():
    print("//! Unicode tables for Python compatible text handling. Generated by")
    print("//! `tools/gen_unicode_tables.py`; do not edit.")
    print("//!")
    print(f"//! Source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
    print()
    emit("NON_PRINTABLE: &[(u32, u32)]",
         "Inclusive ranges of the code points for which `str.isprintable` is false.",
         (f"(0x{a:X}, 0x{b:X})" for a, b in ranges(lambda c: not c.isprintable())))
    zeros = sorted({code - unicodedata.decimal(chr(code))
                    for code in range(0x110000)
                    if not 0xD800 <= code <= 0xDFFF and unicodedata.decimal(chr(code), None) is not None})
    emit("DECIMAL_ZEROS: &[u32]", "The digit zero of each run of ten decimal digits.",
         (f"0x{zero:X}" for zero in zeros))
    emit("SPACES: &[(u32, u32)]", "Inclusive ranges of the code points for which `str.isspace` is true.",
         (f"(0x{a:X}, 0x{b:X})" for a, b in ranges(lambda c: c.isspace())))


main()
